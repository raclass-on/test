// 숙제 성취도 별점 기준 (정답률 %에 따라 별 개수 결정)
//  위에서부터 조건을 만족하는 첫 번째 별 개수를 사용합니다.
export const starRules = [
  { min: 90, stars: 5 },
  { min: 75, stars: 4 },
  { min: 60, stars: 3 },
  { min: 40, stars: 2 },
  { min: 0, stars: 1 },
]

export function starsFor(percent) {
  const rule = starRules.find((r) => percent >= r.min)
  return rule ? rule.stars : 1
}
